"""Export candidate roads for the review page (review/index.html).

    python -m pipeline review --region shreveport

Writes review/roads.js (generated, not committed). Open review/index.html
through any static server, mark each road, and export your verdicts to
data/review/verdicts.json; `score` uses them as overrides and the surface
classifier uses them as extra training labels.
"""
from __future__ import annotations

import argparse
import json

import shapely

from .config import REPO, load_region
from .report import DEFAULT_MIN_LENGTH_M, speed_text, surface_text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--region", default="shreveport")
    ap.add_argument("--top", type=int, default=300)
    args = ap.parse_args()
    region = load_region(args.region)
    fc = json.loads((region.out_dir / "candidates.geojson").read_text(encoding="utf-8"))
    feats = [f for f in fc["features"] if f["properties"]["length_m"] >= DEFAULT_MIN_LENGTH_M]
    by_score = sorted(feats, key=lambda f: -f["properties"]["score_overall"])
    drivers = [f for f in by_score if f["properties"]["drivers_road"]]
    local = [f for f in drivers if f["properties"]["home_mi"] <= region.local_radius_mi]
    gravel = [f for f in by_score if f["properties"].get("gravel_road")]
    unsure = [f for f in by_score if not f["properties"]["drivers_road"] and f["properties"].get("surface_check")
              and not f["properties"].get("gravel_road")]
    left_out = [f for f in by_score if not f["properties"]["drivers_road"] and not f["properties"].get("gravel_road")
                and not f["properties"].get("surface_check")]
    chosen, seen = [], set()
    for group, items in (("drivers", drivers[: args.top]), ("local", local[:100]),
                         ("unsure", unsure[:150]), ("gravel", gravel[:60]), ("left_out", left_out[:60])):
        for f in items:
            pid = f["properties"]["id"]
            if pid in seen:
                continue
            seen.add(pid)
            chosen.append((group, f))
    out = []
    for group, f in chosen:
        p = f["properties"]
        line = shapely.LineString(f["geometry"]["coordinates"]).simplify(0.00003)
        out.append({
            "id": p["id"], "group": group, "name": p["name"], "near": p["near"],
            "miles": round(p["length_m"] / 1609.344, 1), "home_mi": p["home_mi"],
            "overall": p["score_overall"], "twisty": p["score_twisty"], "speed": p["score_speed"],
            "flow": p["score_flow"], "elevation": p["score_elevation"], "scenic": p["score_scenic"],
            "speed_text": speed_text(p), "surface_text": surface_text(p),
            "excluded": p["not_drivers_road_because"], "homes_per_km": p.get("homes_per_km"),
            "coords": [[round(x, 5), round(y, 5)] for x, y in line.coords],
        })
    dest = REPO / "review" / "roads.js"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(
        "// Generated by `python -m pipeline review`. Map data (c) OpenStreetMap contributors, ODbL.\n"
        f"window.ROADS = {json.dumps(out)};\nwindow.REGION = {json.dumps({'name': region.name, 'home': region.home, 'local_radius_mi': region.local_radius_mi})};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(out)} roads to {dest}")

    # One-file copy that opens straight from disk (double-click), no server needed.
    page = (REPO / "review" / "index.html").read_text(encoding="utf-8")
    for name in ("theme.js", "roads.js"):
        js = (REPO / "review" / name).read_text(encoding="utf-8")
        page = page.replace(f'<script src="{name}"></script>', "<script>\n" + js + "\n</script>")
    bundle = REPO / "review" / "road-check.html"
    bundle.write_text(page, encoding="utf-8")
    print(f"wrote {bundle}")


if __name__ == "__main__":
    main()
